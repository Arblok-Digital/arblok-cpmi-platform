const TZ_OFFSET = 7 * 60 // Asia/Jakarta (no DST)
const NOW = Date.now()

function at(daysAgo: number, hour = 9, minute = 0): string {
  const d = new Date(NOW - daysAgo * 86400000)
  const utcMidnight = Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate())
  return new Date(utcMidnight + (hour * 60 + minute - TZ_OFFSET) * 60000).toISOString()
}

function trail(
  candidate: Candidate,
  upTo: CandidateStatus,
  startDaysAgo: number,
  actorId: string,
  actorName: string,
): StatusEvent[] {
  const index = STATUS_ORDER.indexOf(upTo)
  const statuses = STATUS_ORDER.slice(0, index + 1)
  const step = Math.max((startDaysAgo - 0.3) / Math.max(statuses.length, 1), 0.4)
  return statuses.map((status, i) => ({
    id: `se-${candidate.id}-${i}`,
    candidateId: candidate.id,
    orgId: candidate.orgId,
    fromStatus: i === 0 ? undefined : statuses[i - 1],
    toStatus: status,
    actorUserId: i === 0 ? candidate.createdBy : actorId,
    actorName: i === 0 ? 'Agen sumber' : actorName,
    reason:
      i === 0
        ? 'Referral diterima dan status awal dicatat.'
        : i === statuses.length - 1
          ? 'Status diperbarui sesuai proses yang berjalan.'
          : undefined,
    visibility: 'candidate',
    createdAt: at(Math.max(startDaysAgo - i * step, 0.2), 10 + (i % 6)),
  }))
}

